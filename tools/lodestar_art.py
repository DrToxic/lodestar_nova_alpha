#!/usr/bin/env python3
"""Original 1-bit emblems (40x60) for the LODESTAR family: NOVA, ORION, PULSAR, HEARTH. By FEAR REACTIVE.
Library: logo(name) -> PIL image mode "1".  CLI: python lodestar_art.py header NAME OUT.h"""
import math, sys
from PIL import Image, ImageDraw
W, H = 40, 60

def _star(d, cx, cy, R, r, pts=4, rot=-90, fill=1):
    p = []
    for i in range(pts * 2):
        a = math.radians(rot + i * 180 / pts)
        rad = R if i % 2 == 0 else r
        p.append((cx + rad * math.cos(a), cy + rad * math.sin(a)))
    d.polygon(p, fill=fill)

def nova():
    # a nova: a star flaring into a burst (eight rays) with a bright core and a ring of ejecta
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im); cx, cy = 20, 30
    _star(d, cx, cy, 29, 3, pts=4, rot=-90)             # long cardinal rays
    _star(d, cx, cy, 15, 3, pts=4, rot=-45)             # shorter diagonal rays
    d.ellipse((cx - 8, cy - 8, cx + 8, cy + 8), fill=0)   # clear a halo
    d.ellipse((cx - 7, cy - 7, cx + 7, cy + 7), outline=1)  # ring of ejecta
    d.ellipse((cx - 4, cy - 4, cx + 4, cy + 4), fill=1)   # core
    return im

def orion():
    # the Orion constellation: shoulders, belt, knees, joined by lines, plus the sword
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im)
    S = {"bet": (8, 8), "bel": (31, 11), "mint": (14, 28), "alni": (20, 29), "alnit": (26, 30),
         "saiph": (31, 53), "rigel": (8, 51), "head": (19, 3)}
    for a, b in [("bet", "mint"), ("bel", "alnit"), ("mint", "alni"), ("alni", "alnit"), ("mint", "rigel"), ("alnit", "saiph"), ("bet", "head"), ("bel", "head")]:
        d.line((S[a], S[b]), fill=1)
    d.line((20, 33, 20, 41), fill=1)                      # sword
    def dot(p, r): d.ellipse((p[0] - r, p[1] - r, p[0] + r, p[1] + r), fill=1)
    for k, r in [("bet", 4), ("bel", 3), ("mint", 2), ("alni", 2), ("alnit", 2), ("saiph", 3), ("rigel", 4)]: dot(S[k], r)
    dot((20, 41), 1); dot(S["head"], 1)
    for k in ("bet", "rigel"):                            # the two bright stars get a small cross flare
        x, y = S[k]; d.line((x - 6, y, x + 6, y), fill=1); d.line((x, y - 6, x, y + 6), fill=1)
        d.ellipse((x - 3, y - 3, x + 3, y + 3), fill=0); d.ellipse((x - 2, y - 2, x + 2, y + 2), fill=1)
    return im

def pulsar():
    # a pulsar: a tiny dense star with two opposite beams sweeping out, and rings pulsing from it
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im); cx, cy = 20, 30
    for sgn in (-1, 1):                                   # beam cones along a tilted axis
        ang = math.radians(-65 if sgn < 0 else 115)
        ex, ey = cx + 25 * math.cos(ang), cy + 25 * math.sin(ang)
        px, py = -math.sin(ang), math.cos(ang)
        d.polygon([(cx, cy), (ex + px * 5, ey + py * 5), (ex - px * 5, ey - py * 5)], fill=1)
    d.ellipse((cx - 9, cy - 9, cx + 9, cy + 9), fill=0)
    d.ellipse((cx - 8, cy - 8, cx + 8, cy + 8), outline=1)
    d.ellipse((cx - 4, cy - 4, cx + 4, cy + 4), fill=1)
    return im

def hearth():
    # a hearth: a flame over crossed logs, inside a fireplace arch
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im)
    d.rounded_rectangle((1, 4, 38, 59), radius=17, outline=1)      # the arch
    d.rounded_rectangle((3, 6, 36, 57), radius=15, outline=1)
    # flame (outer teardrop with a notch) and inner flame cut out
    outer = [(20, 12), (26, 22), (30, 30), (29, 38), (24, 43), (16, 43), (11, 38), (10, 30), (14, 24), (16, 28), (18, 22)]
    d.polygon(outer, fill=1)
    inner = [(20, 28), (24, 34), (24, 39), (20, 42), (16, 39), (16, 34)]
    d.polygon(inner, fill=0)
    d.ellipse((18, 36, 22, 41), fill=1)
    # logs
    d.line((9, 54, 31, 45), fill=1, width=3); d.line((31, 54, 9, 45), fill=1, width=3)
    d.ellipse((6, 52, 11, 57), fill=1); d.ellipse((29, 52, 34, 57), fill=1)
    return im

LOGOS = {"nova": nova, "orion": orion, "pulsar": pulsar, "hearth": hearth}
def logo(name): return LOGOS[name]()

def header_text(im, name):
    rows = []
    for y in range(H):
        for xb in range(0, W, 8):
            v = 0
            for b in range(8): v = (v << 1) | (1 if xb + b < W and im.getpixel((xb + b, y)) else 0)
            rows.append(v)
    body = "\n".join("  " + ", ".join("0x%02X" % x for x in rows[i:i + W // 8]) + "," for i in range(0, len(rows), W // 8))
    return f"""// LODESTAR {name.upper()} emblem. {W}x{H}, 1 bit per pixel, MSB first. Original artwork by FEAR REACTIVE.
// Generated by tools/lodestar_art.py - do not edit by hand.
#pragma once
#include <stdint.h>
#ifndef PROGMEM
#define PROGMEM
#endif
#define {name.upper()}_LOGO_W {W}
#define {name.upper()}_LOGO_H {H}
static const uint8_t {name}_logo[] PROGMEM = {{
{body}
}};
"""

if __name__ == "__main__":
    if sys.argv[1] == "sheet":
        out = Image.new("RGB", (4 * (W * 8 + 20) + 20, H * 8 + 40), (20, 20, 20))
        for i, n in enumerate(LOGOS):
            out.paste(logo(n).convert("RGB").resize((W * 8, H * 8), Image.NEAREST), (20 + i * (W * 8 + 20), 20))
        out.save(sys.argv[2])
